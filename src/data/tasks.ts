export function getTasksByVocation(vocation: string): TaskDefinition[] {
  switch (vocation) {
    case 'lavrador':
      return LAVRADOR_TASKS;
    case 'andarilho':
      return ANDARILHO_TASKS;
    case 'aprendiz_artesao':
      return ARTESAO_TASKS;
    case 'aspirante_guarda':
      return GUARDA_TASKS;
    case 'comerciante_ambulante':
      return COMERCIANTE_TASKS;
    default:
      return [];
  }
}

export function getAllTasks(): TaskDefinition[] {
  return [
    ...UNIVERSAL_TASKS,
    ...LAVRADOR_TASKS,
    ...ANDARILHO_TASKS,
    ...ARTESAO_TASKS,
    ...GUARDA_TASKS,
    ...COMERCIANTE_TASKS,
  ];
}

export function getTaskById(id: string): TaskDefinition | undefined {
  return getAllTasks().find((t) => t.id === id);
}

